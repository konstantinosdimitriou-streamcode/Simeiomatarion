#import "Localization.h"

static NSString *LanguageSetting = @"system";

NSString *NppUILanguage(void) {
	return LanguageSetting ?: @"system";
}

void NppSetUILanguage(NSString *language) {
	if ([language isEqualToString:@"en"] || [language isEqualToString:@"el"] || [language isEqualToString:@"system"]) {
		LanguageSetting = [language copy];
	} else {
		LanguageSetting = @"system";
	}
}

BOOL NppUseGreek(void) {
	if ([LanguageSetting isEqualToString:@"el"]) {
		return YES;
	}
	if ([LanguageSetting isEqualToString:@"en"]) {
		return NO;
	}
	return [NSLocale.preferredLanguages.firstObject hasPrefix:@"el"];
}

